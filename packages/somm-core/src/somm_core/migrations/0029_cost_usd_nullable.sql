-- Migration 0029 — calls.cost_usd may be NULL: the price was not known.
--
-- 0001 declared cost_usd NOT NULL DEFAULT 0.0, so a call whose price somm
-- did not know (a self-hosted endpoint, an unlisted model) was recorded as
-- free, and looked free in every cost-per-call comparison. NULL now means
-- unknown; 0.0 means free.
--
-- SQLite cannot drop a NOT NULL constraint with ALTER TABLE, and rebuilding
-- calls would rewrite the whole ledger. Removing a NOT NULL constraint does
-- not change the stored rows, so somm_core.schema edits the table's stored
-- definition in place, the procedure SQLite documents for exactly this
-- change (https://www.sqlite.org/lang_altertable.html#otheralter). This file
-- carries no statements; the step lives in schema._relax_cost_usd_not_null.
